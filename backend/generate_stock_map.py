def fetch_from_akshare():
    """从 AKShare 获取全市场股票代码和名称"""
    try:
        import akshare as ak
        df = ak.stock_zh_a_spot_em()
        result = {}
        for _, row in df.iterrows():
            code = str(row['代码'])
            name = str(row['名称'])
            result[code] = name
        return result
    except Exception as e:
        print(f"AKShare 获取失败: {e}")
        return None


def main():
    # 创建 data 目录
    script_dir = os.path.dirname(os.path.abspath(__file__))
    data_dir = os.path.join(script_dir, "data")
    os.makedirs(data_dir, exist_ok=True)

    output_file = os.path.join(data_dir, "stock_name_map.json")

    # 尝试从 AKShare 获取
    print("尝试从 AKShare 获取全市场股票代码和名称...")
    stock_map = None
    for attempt in range(3):
        print(f"  尝试 {attempt + 1}/3...")
        stock_map = fetch_from_akshare()
        if stock_map:
            print(f"  成功获取 {len(stock_map)} 只股票")
            break
        time.sleep(2)

    if not stock_map:
        print("AKShare 获取失败，使用内置的常见股票映射")
        stock_map = dict(BUILTIN_MAP)

    # 用内置映射补充（确保关键股票都有名称）
    for code, name in BUILTIN_MAP.items():
        if code not in stock_map:
            stock_map[code] = name

    # 保存到 JSON 文件
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(stock_map, f, ensure_ascii=False, indent=2)

    print(f"已保存 {len(stock_map)} 只股票名称到: {output_file}")
    print(f"文件大小: {os.path.getsize(output_file) / 1024:.1f} KB")


if __name__ == "__main__":
    main()
